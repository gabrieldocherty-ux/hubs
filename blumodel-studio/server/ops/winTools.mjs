// Windows: the small tools a deploy writes into the home next to run-server.cmd, and what the
// installer puts on the desktop (docs/HOSTING.md, "Turning the sites off and on" and "Automatic
// updates"; WYSE_SETUP.md):
//   blumodel.cmd       `blumodel sites on|off|status` (scripts/host/blumodel.mjs in the checkout)
//   update-now.cmd     "Update BluModel": runs the update directly (scripts/host/update.mjs) in a
//                      window that stays open with the result; the fallback when the server, and so
//                      the face's Update now, is down
//   blumodel.ico       the app's icon for the shortcuts (an ICO holding the 192 px PNG)
//   BluModel Server.url (on the desktop) http://127.0.0.1:8799, the server face
// Pure text and bytes; nothing here writes, registers or starts anything.

import { crlf } from './home.mjs';

/**
 * blumodel.cmd and update-now.cmd, CRLF. Both use the install's checkout in <home>\repo and
 * refuse with a plain message when there is none (a PC that deploys from a development checkout).
 * @param {{ node: string }} o
 */
export function toolScripts({ node }) {
  if (!node || /["%\r\n]/.test(node)) throw new Error('toolScripts needs the node.exe path (no quotes or %)');
  const blumodel = `@echo off
rem blumodel sites on^|off^|status: every site on, or off for maintenance (docs/HOSTING.md,
rem "Turning the sites off and on"). Talks to the running server's face on 127.0.0.1; no admin needed.
rem Generated by blumodel-studio/scripts/deploy-local.mjs (server/ops/winTools.mjs): edits are overwritten.
setlocal
set "S=%~dp0repo\\blumodel-studio\\scripts\\host\\blumodel.mjs"
if not exist "%S%" (
  echo blumodel.cmd needs the install's checkout, %S%, which is not there.
  exit /b 1
)
"${node}" --no-warnings "%S%" %*
exit /b %errorlevel%
`;
  const update = `@echo off
title Update BluModel
rem "Update BluModel" on the desktop: runs the update now, directly (scripts\\host\\update.mjs: pull the
rem release, back up the database, deploy, health check, roll back if unhealthy), and keeps this
rem window open with the result. The fallback when the server face's Update now can't be reached.
rem Generated by blumodel-studio/scripts/deploy-local.mjs (server/ops/winTools.mjs): edits are overwritten.
setlocal
cd /d "%~dp0"
set "S=%~dp0repo\\blumodel-studio\\scripts\\host\\update.mjs"
if not exist "%S%" (
  echo There is no install checkout at %S%, so there is nothing to update from.
  pause
  exit /b 1
)
echo Updating BluModel Studio from GitHub. The site is down for a few seconds if there is a new release.
echo.
"${node}" --no-warnings "%S%" --home "%~dp0."
set CODE=%errorlevel%
echo.
if "%CODE%"=="0" (echo Done: BluModel Studio is up to date and running.) else (echo The update did not finish ^(exit %CODE%^): read the lines above, and logs\\update.log. The site runs the version it had.)
echo.
pause
exit /b %CODE%
`;
  return { 'blumodel.cmd': crlf(blumodel), 'update-now.cmd': crlf(update) };
}

/** The desktop's "BluModel Server.url": the server face in the default browser. */
export function faceShortcut({ port = 8799, icon = null } = {}) {
  const p = Number(port);
  if (!Number.isInteger(p) || p < 1 || p > 65535) throw new Error(`Not a port: ${port}`);
  return crlf(`[InternetShortcut]\nURL=http://127.0.0.1:${p}/\n${icon ? `IconFile=${icon}\nIconIndex=0\n` : ''}`);
}

/**
 * An .ico holding one PNG image (Windows Vista and later read PNG-compressed icons). The size comes
 * from the PNG's IHDR; 256 px and up is written as 0, as the format says.
 * @param {Buffer} png
 */
export function icoFromPng(png) {
  if (!Buffer.isBuffer(png) || png.length < 24 || png.readUInt32BE(0) !== 0x89504e47 || png.toString('ascii', 12, 16) !== 'IHDR') throw new Error('icoFromPng needs a PNG');
  const w = png.readUInt32BE(16);
  const h = png.readUInt32BE(20);
  const head = Buffer.alloc(6 + 16);
  head.writeUInt16LE(0, 0); // reserved
  head.writeUInt16LE(1, 2); // icon
  head.writeUInt16LE(1, 4); // one image
  head.writeUInt8(w >= 256 ? 0 : w, 6);
  head.writeUInt8(h >= 256 ? 0 : h, 7);
  head.writeUInt8(0, 8); // no palette
  head.writeUInt8(0, 9);
  head.writeUInt16LE(1, 10); // planes
  head.writeUInt16LE(32, 12); // bits per pixel
  head.writeUInt32LE(png.length, 14);
  head.writeUInt32LE(22, 18); // offset of the image
  return Buffer.concat([head, png]);
}
